import type { Product, ProductOption, ProductVariant } from "@/lib/types";

/** Builds the cartesian set of variants for a product's options. */
function variants(
  skuBase: string,
  options: ProductOption[],
  price: (o: Record<string, string>) => number,
  opts: { compareAt?: (o: Record<string, string>) => number | undefined; stock?: (o: Record<string, string>) => number } = {},
): ProductVariant[] {
  const combos: Record<string, string>[] = options.reduce<Record<string, string>[]>(
    (acc, opt) => acc.flatMap((c) => opt.values.map((v) => ({ ...c, [opt.name]: v }))),
    [{}],
  );
  return combos.map((o) => ({
    sku: [skuBase, ...Object.values(o).map((v) => v.replace(/[^a-z0-9]/gi, "").toUpperCase().slice(0, 4))].join("-"),
    options: o,
    price: price(o),
    compareAtPrice: opts.compareAt?.(o),
    stock: opts.stock ? opts.stock(o) : 24,
  }));
}

